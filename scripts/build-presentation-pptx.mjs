// Helper to draw a styled content card
function addCard(slide, { x, y, w, h, title, icon, items, bg = C_CARD, borderColor = C_BORDER, titleColor = C_TEXT }) {
  // Card background
  slide.addShape("roundRect", {
    x, y, w, h,
    rectRadius: 0.12,
    fill: { color: bg },
    line: { color: borderColor, width: 1.2 }
  });

  // Card header
  slide.addText(`${icon ? icon + "  " : ""}${title}`, {
    x: x + 0.25, y: y + 0.2, w: w - 0.5, h: 0.45,
    fontSize: 15, bold: true, color: titleColor,
    valign: "middle"
  });

  // Bullet items
  if (Array.isArray(items)) {
    const textObjects = items.map((it, idx) => ({
      text: it,
      options: {
        fontSize: 12,
        color: "334155",
        bullet: { type: "bullet", code: "2022" },
        spacing: { after: idx === items.length - 1 ? 0 : 8 }
      }
    }));
    slide.addText(textObjects, {
      x: x + 0.25, y: y + 0.75, w: w - 0.5, h: h - 0.95,
      valign: "top"
    });
  }
}

