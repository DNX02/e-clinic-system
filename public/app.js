function translateSurveyDynamicText(value) {
  if (surveyLanguage() !== "tg") return value;
  const replacements = [
    "Сердечно-сосудистый риск",
    "Систолическое АД",
    "Очень высокий",
    "Слегка повышенный",
    "Повышенный риск",
    "Умеренный",
    "Высокий",
    "Низкий",
    "баллов",
    "факторы",
    "возраст",
    "мужской пол",
    "курение",
    "повышенное САД",
    "мм рт.ст."
  ];
  return replacements.reduce((text, item) => text.replaceAll(item, translateSurveyText(item)), String(value || ""));
}

